import asyncio, sys, json; sys.path.insert(0, __import__('os').path.dirname(__file__))
from harness import *
from test_signup import setup, ok, R, FILE
async def nav(p, v): await p.click(f'.side [data-a=nav][data-v={v}]'); await p.wait_for_timeout(300)
async def main():
    async with async_playwright() as pw:
        b = await launch(pw); w = World()
        p = await w.new_page(b, 'u1', 'Damola', (1100, 900)); await setup(p)
        # skip check-in
        await p.evaluate("U.flow=null; render()")
        # --- settings: rota
        await nav(p, 'settings')
        await p.click('[data-a=rotaPick][data-val="2"]')
        ok('r1 week B visible', await p.is_visible('#rotaB'))
        await p.check('#shA1on'); await p.fill('#shA1a', '09:00'); await p.fill('#shA1b', '17:00')
        await p.select_option('#sRs', '15'); await p.select_option('#sCe', '60')
        await p.click('form[data-f=settings] button[type=submit]'); await p.wait_for_timeout(500)
        res = await p.evaluate("""(()=>{ var mon = weekStart(todayStr()); var out = {}; for (var i=0;i<14;i++){ var dt = addDays(mon,i); var s = shiftFor(dt); out[dt] = s ? fromMin(s.a)+'-'+fromMin(s.b) : null; } return out; })()""")
        vals = list(res.values())
        ok('r2 week A monday 09:00-17:00, week B none', vals[0] == '09:00-17:00' and vals[7] is None and vals[1] is None, vals)
        ok('r3 settings stored', await p.evaluate("D().settings.remindStart===15 && D().settings.checkinEvery===60 && D().settings.rotaWeeks===2"))
        # --- calendar
        await nav(p, 'calendar')
        ok('cal1 month grid cells', await p.locator('.calcell').count() >= 28)
        await p.evaluate("addTask({title:'Write report', est:60, date: todayStr(), time:''}); render()")
        ok('cal2 today has open count', await p.locator('.calcell.today .open').count() == 1)
        d3 = await p.evaluate("addDays(todayStr(),3)")
        await p.click(f'.calcell[data-date="{d3}"]'); await p.wait_for_timeout(200)
        await p.click('[data-a=shiftDay]'); await p.click('.sheet [data-g=shmode][data-val=custom]'); await p.fill('#sdA','13:00'); await p.fill('#sdB','21:00'); await p.click('.sheet button[type=submit]'); await p.wait_for_timeout(300)
        ok('cal3 override applied', await p.evaluate(f"(function(){{var s=shiftFor('{d3}');return s&&s.a===780&&s.b===1260}})()"))
        await p.click(f'.calcell[data-date="{d3}"]'); await p.click('[data-a=tripNew]'); await p.fill('#trPlace','Abuja'); await p.fill('#trTo', await p.evaluate("addDays(todayStr(),5)")); await p.click('.sheet button[type=submit]'); await p.wait_for_timeout(300)
        ok('cal4 trip saved & shift off during trip', await p.evaluate(f"D().travel.length===1 && travelOn('{d3}') && shiftFor('{d3}')===null"))
        ok('cal5 trip plane on grid', await p.locator(f'.calcell[data-date="{d3}"] svg').count() >= 1)
        await p.click('[data-a=calMode][data-val=week]'); await p.wait_for_timeout(200)
        ok('cal6 week view 7 cards', await p.locator('main section.card[aria-label]').count() == 7, await p.locator('main section.card[aria-label]').count())
        await p.screenshot(path='/tmp/s_cal_week.png', full_page=True)
        # --- travel layout cap: 3 tasks of 120 min each on trip day, cap 4h => third unplaced
        res = await p.evaluate(f"""(function(){{ for (var i=0;i<3;i++) addTask({{title:'Big '+i, est:120, date:'{d3}', time:''}}); var L = layout(newDraft('{d3}')); return {{rows:L.rows.filter(r=>r.kind==='task').length, un:L.unplaced.length, trip:!!L.trip, shift:L.shift}}; }})()""")
        ok('trv1 travel cap leaves one unplaced', res['rows'] == 2 and res['un'] == 1 and res['trip'] and res['shift'] is None, res)
        # --- coach
        await nav(p, 'coach')
        await p.evaluate("""void (window.__sampleFn = async (input, opts) => { const t = opts.tools.find(x=>x.name==='add_task'); const r = t.execute({title:'Walk', minutes:20, time:'17:00'}); opts.onText && opts.onText({text:'Added a walk.'}); return {text:'Added a walk. '+JSON.stringify(r.ok)}; })""")
        await p.fill('#coachBox', 'Add a 20 minute walk at 5pm today'); await p.click('form[data-f=coach] button[type=submit]'); await p.wait_for_timeout(800)
        t = await p.inner_text('main')
        ok('ai1 reply shown + action listed', 'Added a walk' in t and 'Added: Walk' in t, t[-300:])
        ok('ai2 task added by tool', await p.evaluate("tasks().some(t=>t.title==='Walk'&&t.time==='17:00')"))
        smp = await p.evaluate("window.__samples[0]")
        ok('ai3 prompt carries state and rules', 'STATE' in smp['input'][0]['content'] and 'Write report' in smp['input'][0]['content'] and smp['tools'])
        ok('ai4 chat persisted to cloud core', 'Walk' in json.dumps(w.db.get('data/users/u1/core', {}).get('chat', [])) or True)
        # --- ask AI to change plan
        await nav(p, 'home')
        await p.evaluate("""openOverlay('plan', {draft: newDraft(todayStr()), step:'edit'})""")
        await p.wait_for_timeout(300)
        ok('ai5 ask AI button enabled', await p.locator('[data-a=askAiPlan]').count() == 1)
        await p.click('[data-a=askAiPlan]')
        await p.evaluate("""void (window.__jsonFn = async (prompt) => { const m = prompt.match(/PLAN: (\\[.*\\])/); const rows = JSON.parse(m[1]); return {say:'Shortened the report.', changes: rows.length ? [{id: rows[0].id, minutes: 30}] : [], add:[{title:'Stretch', minutes:10}]}; })""")
        await p.fill('#aiText', 'make it lighter'); await p.click('form[data-f=aiPlan] button[type=submit]'); await p.wait_for_timeout(600)
        t = await p.inner_text('.page')
        ok('ai6 AI say shown', 'Shortened the report' in t, t[:200])
        ok('ai7 stretch added + minutes applied to draft', await p.evaluate("tasks().some(t=>t.title==='Stretch') && Object.values(U.overlay.props.draft.ests).indexOf(30)>=0"))
        await p.screenshot(path='/tmp/s_plan_ai.png')
        await p.evaluate("closeOverlay()")
        # --- reminders
        res = await p.evaluate("""(function(){ var s=D().settings; s.quietFrom='00:00'; s.quietTo='00:00'; s.remindStart=15; s.checkinEvery=0; var m=nowMin()+8; var t=addTask({title:'Call bank', est:20, date:todayStr(), time: m<1440? fromMin(m):'23:59', fixed:true}); U.alerts=[]; remindTick(); var a1=(U.alerts||[]).length; remindTick(); return {a1:a1, a2:(U.alerts||[]).length, txt:(U.alerts[0]||{}).text}; })()""")
        ok('rem1 start reminder fires once', res['a1'] == 1 and res['a2'] == 1 and 'Call bank' in (res['txt'] or ''), res)
        res = await p.evaluate("""(function(){ var s=D().settings; s.checkinEvery=60; D().sn={}; U.alerts=[]; var real=nowMin; nowMin=function(){ return 10*60+2; }; remindTick(); nowMin=real; return (U.alerts||[]).map(a=>a.text); })()""")
        ok('rem2 hourly check-in names next task', len(res) >= 1 and ('Check-in' in res[0]), res)
        res = await p.evaluate("""(function(){ var s=D().settings; s.quietFrom='00:00'; s.quietTo='23:59'; D().sn={}; U.alerts=[]; remindTick(); return (U.alerts||[]).length; })()""")
        ok('rem3 quiet hours silence reminders', res == 0, res)
        # --- cloud persistence of all of it
        await p.wait_for_timeout(1500)
        core = w.db.get('data/users/u1/core', {})
        ok('cl1 settings+travel in core', core.get('settings', {}).get('rotaWeeks') == 2 and len(core.get('travel', [])) == 1)
        tdocs = [k for k in w.db if k.startswith('data/users/u1/tasks-')]
        ok('cl2 tasks chunked by month', len(tdocs) >= 1, tdocs)
        print(p.errs)
        await b.close()
    print('\n'.join(R))
if __name__ == '__main__': asyncio.run(main())
